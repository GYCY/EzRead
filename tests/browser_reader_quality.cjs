const {chromium} = require(process.env.EZREAD_PLAYWRIGHT || 'playwright');
const path = require('node:path'), assert = require('node:assert/strict'), fs = require('node:fs');
const root = process.env.EZREAD_TEST_ROOT, origin = process.env.EZREAD_TEST_URL, pid = '0123456789abcdef';
const edge = process.env.EZREAD_BROWSER || path.join(process.env['PROGRAMFILES(X86)'] || 'C:/Program Files (x86)', 'Microsoft/Edge/Application/msedge.exe');
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: edge});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}}), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin); await page.waitForSelector('.paper-card');
    const card = page.locator('.paper-card').first();
    await page.evaluate(() => document.fonts.ready);
    await card.locator("img").evaluateAll(nodes => Promise.all(nodes.map(n => n.decode().catch(() => {}))));
    await page.waitForTimeout(200);
    const geometry = await card.boundingBox();
    await card.hover();
    await page.waitForTimeout(200);
    assert.deepEqual(await card.boundingBox(), geometry);
    assert.equal(await card.evaluate(n => getComputedStyle(n).transform), 'none');
    assert.equal(await card.evaluate(n => getComputedStyle(n).cursor), 'pointer');
    await page.evaluate(id => openReader(id), pid);
    assert.equal(await page.getByText('含公式 · 请核对原文', {exact: true}).count(), 0);
    assert.equal(await page.getByText(/本页左栏读完/).count(), 0);
    assert.equal(await page.getByRole('button', {name: '全文术语表', exact: true}).count(), 0);
    const modal = page.locator('#reader-quality-dialog');
    const before = (await (await page.request.get(origin + '/__test/state')).json()).doc;
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    async function cropRegion(box, number = 1, simulateFailure = false) {
      const sourceImage = modal.locator(`.quality-crop-canvas[data-page="${number}"] img`);
      await sourceImage.evaluate(n => n.decode());
      const crop = await sourceImage.boundingBox();
      await page.mouse.move(crop.x + crop.width * box[0], crop.y + crop.height * box[1]);
      await page.mouse.down();
      await page.mouse.move(crop.x + crop.width * box[2], crop.y + crop.height * box[3], {steps: 6});
      await page.mouse.up();
      const add = modal.getByRole('button', {name: '添加框选区域', exact: true});
      let unexpectedRequests = 0;
      if (simulateFailure) await page.route('**/formulas', async route => {
        unexpectedRequests++;
        await route.fulfill({status: 400, contentType: 'application/json', body: JSON.stringify({error: '无效的阅读核对操作。'})});
      });
      await add.click();
      if (simulateFailure) {
        assert.equal(unexpectedRequests, 0);
        assert.equal(await add.isDisabled(), false);
        await page.unroute('**/formulas');
      }
      await page.waitForFunction(() => document.querySelector('#reader-quality-dialog [role=status]').textContent.includes('已添加'));
    }
    async function finish(incomplete = false) {
      await modal.getByRole('button', {name: '完成校对并翻译', exact: true}).click();
      await page.waitForFunction(incomplete => document.querySelector('#reader-quality-dialog [role=status]').textContent.startsWith(incomplete ? '校对已保存，部分' : '校对完成'), incomplete);
      await modal.getByRole('button', {name: '关闭', exact: true}).click();
    }
    await cropRegion([.09, .39, .86, .46], 1, true);
    const staged = (await (await page.request.get(origin + "/__test/state")).json()).doc;
    assert.equal(staged.formula_review, undefined);
    await page.screenshot({path: path.join(root, "work/reader-correction-dialog.png")});
    await finish();
    await page.locator('.reader-formula-image').waitFor();
    const saved = (await (await page.request.get(origin + '/__test/state')).json()).doc;
    assert.equal(saved.blocks[1].translation, before.blocks[1].translation);
    assert.equal(saved.blocks[1].text, before.blocks[1].text);
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    await page.locator('.reader-formula-image').waitFor();
    await page.screenshot({path: path.join(root, 'work/reader-quality-formula.png')});
    let tableRequests = 0;
    page.on('request', request => { if (request.url().endsWith('/tables')) tableRequests++; });
    await page.getByText('查看表格翻译', {exact: true}).waitFor();
    assert.equal(await page.locator('.reader-table-details').evaluate(n => n.open), false);
    await page.getByText('查看表格翻译', {exact: true}).click();
    assert.equal(tableRequests, 0);
    assert.equal(await page.locator('.reader-chinese-table tr').count(), 2);
    assert.equal(await page.locator('.reader-chinese-table tr').last().innerText(), 'A\t2.0 N');
    await page.setViewportSize({width: 800, height: 600});
    await page.locator('.reader-chinese-table').scrollIntoViewIfNeeded();
    assert(await page.locator('.reader-table-scroll').evaluate(n => n.clientWidth <= n.closest('.translation-block').clientWidth));
    await page.screenshot({path: path.join(root, 'work/reader-quality-table.png')});
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    await page.getByText('查看表格翻译', {exact: true}).waitFor();
    await page.setViewportSize({width: 1440, height: 1000});
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    const formulaBox = modal.locator('.quality-existing-region[aria-label="取消识别：公式"]');
    await formulaBox.click();
    assert.equal(await formulaBox.count(), 0);
    await modal.getByRole('button', {name: '恢复识别：公式', exact: true}).click();
    assert.equal(await formulaBox.count(), 1);
    await formulaBox.click();
    assert.equal(await formulaBox.count(), 0);
    await finish();
    assert.equal(await page.locator('.reader-formula-image').count(), 0);
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    await modal.locator('.quality-crop-canvas').first().waitFor();
    await page.evaluate(() => { const n = document.querySelector('#reader-quality-dialog select[aria-label="区域类型"]'); n.value = 'figure'; n.dispatchEvent(new Event('change', {bubbles: true})); });
    assert.equal(await modal.locator('[aria-label="原文页码"]').count(), 0);
    assert.equal(await modal.locator('.quality-pdf-page').count(), 2);
    const body = modal.locator('.reader-quality-body');
    await body.hover();
    await page.mouse.wheel(0, 1200);
    await page.waitForFunction(() => document.querySelector('#reader-quality-dialog .reader-quality-body').scrollTop > 800);
    const nextImage = modal.locator('.quality-crop-canvas[data-page="2"] img');
    await nextImage.evaluate(n => n.decode());
    // A real wheel event reaches the next PDF page without choosing a page number.
    const nextTop = await nextImage.boundingBox(), bodyBox = await body.boundingBox();
    await page.mouse.wheel(0, nextTop.y - bodyBox.y - 20);
    await page.waitForTimeout(150);
    await cropRegion([.1, .02, .8, .15], 2);
    await page.screenshot({path: path.join(root, 'work/reader-correction-continuous.png')});
    await finish();
    await page.getByText('查看图表翻译', {exact: true}).click();
    const checked = (await (await page.request.get(origin + '/__test/state')).json()).doc;
    assert.equal(checked.formula_regions.find(r => r.region_kind === 'figure').page, 2);
    assert.match(await page.locator('.region-translation-text').innerText(), /模拟图表译文/);
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    await page.getByText('查看图表翻译', {exact: true}).click();
    assert.match(await page.locator('.region-translation-text').innerText(), /模拟图表译文/);
    await page.request.post(origin + '/__test/split-fixture');
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    await cropRegion([.09,.32,.8,.39]);
    await finish();
    assert.equal(await page.locator('.reader-retained-source').count(), 0);
    assert.equal(await page.locator('.translation-block[data-block-id="split-source"]').count(), 0);
    assert.match(await page.locator('#translation-scroll').innerText(), /模拟框外译文：Before retained/);
    const splitSaved = (await (await page.request.get(origin + '/__test/state')).json()).doc;
    assert.equal(splitSaved.blocks[0].translation, '完整旧译文保留');
    assert.equal(splitSaved.blocks[0].note, '保留旧批注');
    assert.equal(splitSaved.text_annotations[0].ranges[0].block_id, 'split-source');
    await page.screenshot({path: path.join(root, 'work/reader-split-retained.png')});
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    assert.equal(await page.locator('.translation-block[data-block-id="split-source"]').count(), 0);
    assert.equal(await page.getByText(/校对前内容/).count(), 0);
    await page.request.post(origin + '/__test/caption-fixture');
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    await finish(true);
    await page.getByRole('button', {name: '校对图表与公式', exact: true}).click();
    assert.match(await modal.locator('.quality-caption-ledger').innerText(), /Figure 1：未识别到图注/);
    assert.match(await modal.locator('.quality-caption-ledger').innerText(), /Figure 12：已识别 · 已翻译/);
    await modal.getByRole('button', {name: '关闭', exact: true}).click();
    assert.match(await page.locator('#translation-scroll').innerText(), /模拟框外译文：Figure 12\. Missing caption/);
    assert.match(await page.locator('#translation-scroll').innerText(), /Caption continuation/);
    await page.reload(); await page.waitForSelector('.paper-card'); await page.evaluate(id => openReader(id), pid);
    assert.match(await page.locator('#translation-scroll').innerText(), /模拟框外译文：Figure 12\. Missing caption/);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(root, 'work/reader-quality-browser.json'), JSON.stringify({errors, realModelCalls: 0, realLibraryWrites: 0, checks: ['no-glossary-view-entry', 'manual-correction-save', 'reload-preserves-overlay-and-original', 'saved-table-expand-without-inference-reload', 'dismiss-region', 'pure-image-add-translate-reload', 'pointer-cursor', 'add-works-with-unsupported-backend-and-no-request', 'add-without-preview-write', 'wheel-across-pdf-pages-and-page-2-crop', 'split-outside-body-and-retain-old-translation-annotations']}, null, 2));
    console.log('Reader quality browser checks passed; real model calls/library writes: 0.');
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
